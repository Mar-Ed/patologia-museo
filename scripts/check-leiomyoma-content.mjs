import assert from "node:assert/strict";
import fs from "node:fs";
import { loadContentModules } from "./content-modules.mjs";

const { content } = loadContentModules();
const slug = "leiomioma-en-vacuno";
const record = content.getCaseContent(slug);
assert.ok(record);
assert.ok(!/prune|quistes hepáticos|hipoplasia muscular|vejiga bilobulada|1,5 litros/i.test(JSON.stringify(record)), "Do not publish the unrelated Prune Belly case");
assert.equal(record.item.category, "adquirida");
assert.equal(record.item.species, "Bovino");
assert.equal(record.localCases.length, 0, "Published literature is not a clinical record of the museum specimen");
assert.equal(record.documentSections.length, 0, "The supplied document describes a different disease");
assert.deepEqual(Array.from(record.sections, section => section.id), ["concepto", "mecanismo", "morfologia", "diagnostico", "relevancia"]);
assert.ok(record.sections[0].paragraphs.join(" ").includes("tumor mesenquimal benigno"));
assert.ok(record.sections.find(section => section.id === "diagnostico").points.some(point => point.includes("histopatología")));
assert.equal(record.references.length, 3);
for (const reference of record.references) assert.ok(reference.url.startsWith("https://"));
for (const id of ["leiomyoma", "leiomyomaSurgery", "leiomyomaAtlas"]) assert.ok(record.references.some(reference => reference.id === id));
assert.equal(record.videos.length, 0, "The owner removed the leiomyoma video");
const html = fs.readFileSync(`.next/server/app/patologias/${slug}.html`, "utf8");
assert.ok(!html.includes("1tLl4oCJdc3cGtU1y6GJEpSIoiHV0p-Ng"), "The removed video must not appear in production HTML");
assert.ok(!/Prune Belly|quistes hepáticos|vejiga bilobulada|hipoplasia muscular/i.test(html), "Unrelated clinical text must not appear in production HTML or metadata");
for (const phrase of ["neoplasia benigna", "tumor mesenquimal benigno", "histopatología", "infertilidad"]) assert.ok(html.includes(phrase));
const catalogItem = content.getCatalog().find(item => item.slug === slug);
assert.ok(catalogItem.summary.startsWith("El leiomioma es una neoplasia benigna de músculo liso."));
assert.ok(!/prune/i.test(catalogItem.summary));
assert.ok(content.getCaseContent("sindrome-de-prune-belly-y-afasia").documentSections[0].paragraphs[0].startsWith("En 1839 Frohlich"), "Keep the actual Prune Belly pathology intact");
console.log("Leiomyoma: five scientific sections, linked sources, Spanish catalog/production HTML, no video, no fabricated specimen findings and no Prune Belly text: OK.");
